export function tr(text: string, lang: SupportedLang = 'en'): string {
  if (lang === 'en' || !text) return text;
  const idx = E.indexOf(text);
  if (idx >= 0 && L[lang] && L[lang][idx]) {
    return L[lang][idx];
  }
  if (dict[text] && dict[text][lang]) {
    return dict[text][lang];
  }
  return text;
}

export function formatStreak(days: number, lang: SupportedLang = 'en'): string {
  if (lang === 'hi') return `${days} दिन की स्ट्रीक`;
  if (lang === 'es') return `Racha de ${days} ${days === 1 ? 'día' : 'días'}`;
  if (lang === 'fr') return `Série de ${days} ${days > 1 ? 'jours' : 'jour'}`;
  return `${days} day streak`;
}
